export async function adminPage(request: HttpRequest): Promise<HttpResponseInit> {
  const user = getUser(request);
  if (!user || !user.isAdmin) {
    return {
      status: 401,
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
      },
      body: 'Unauthorized',
    };
  }

  return {
    status: 200,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
    },
    body: ADMIN_HTML.join('\n'),
  };
}

app.http('adminPage', {
  methods: ['GET'],
  authLevel: 'anonymous',
  route: 'manage',
  handler: adminPage,
});
